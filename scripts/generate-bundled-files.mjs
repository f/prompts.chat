#!/usr/bin/env node
/**
 * Embeds the small project files that server code reads at runtime into
 * src/lib/bundled-files.generated.ts. Worker hosts (Spacefast, Cloudflare)
 * have no project filesystem, so these files must travel inside the bundle.
 *
 * Usage: node scripts/generate-bundled-files.mjs [--check]
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = "src/lib/bundled-files.generated.ts";

/** Directories whose files are embedded as UTF-8 text, filtered by suffix */
const TEXT_SOURCES = [
  { dir: "src", suffix: ".prompt.yml" },
  { dir: "plugins/claude/prompts.chat/skills", suffix: "" },
];

/** Individual files embedded as base64 */
const BINARY_SOURCES = [
  "public/bots/openclaw.svg",
  "public/bots/hermes.png",
  "public/bots/autogpt.svg",
  "public/bots/dots.svg",
  "public/bots/duet.svg",
  "public/bots/muse.svg",
];

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

function toKey(root, path) {
  return relative(root, path).split(sep).join("/");
}

export function renderBundledFiles(root = ROOT) {
  const text = {};
  for (const { dir, suffix } of TEXT_SOURCES) {
    for (const path of walk(join(root, dir))) {
      if (path.endsWith(suffix)) text[toKey(root, path)] = readFileSync(path, "utf8");
    }
  }
  const binary = {};
  for (const file of BINARY_SOURCES) {
    binary[file] = readFileSync(join(root, file)).toString("base64");
  }
  const sorted = (record) => Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)));
  return [
    "// Generated by scripts/generate-bundled-files.mjs; do not edit. Run `npm run generate:bundled-files`.",
    "",
    `export const BUNDLED_TEXT_FILES: Record<string, string> = ${JSON.stringify(sorted(text), null, 2)};`,
    "",
    `export const BUNDLED_BINARY_FILES: Record<string, string> = ${JSON.stringify(sorted(binary), null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = join(ROOT, OUTPUT);
  const rendered = renderBundledFiles();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(output, "utf8");
    } catch {}
    if (current !== rendered) {
      console.error(`${OUTPUT} is out of date. Run \`npm run generate:bundled-files\`.`);
      process.exit(1);
    }
  } else {
    writeFileSync(output, rendered);
  }
}
